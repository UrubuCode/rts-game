// Bundle pure terrain/geometry code for the runtime's eval-only native workers.
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
let ts;try{ts=require('typescript');}catch{try{ts=require('../engine/node_modules/typescript');}catch{ts=require('../build/engine-audit/node_modules/typescript');}}
const files=['world_streaming.ts','world_geometry.ts'];
const sourceRoot=fs.existsSync('engine/src/engine/core/world_geometry.ts')?'engine/src':'src';
const source=files.map(file=>fs.readFileSync(sourceRoot+'/engine/core/'+file,'utf8').replace(/^import .*;\r?\n/gm,'').replace(/^export /gm,'')).join('\n');
const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.ESNext}}).outputText;
const protocol=`
import { parentPort,workerData,receiveMessageOnPort,isTerminating } from "node:worker_threads";
import { time } from "rts";
try {
 const start=performance.now();
 const job=new FpsWorldChunkJob(new FpsWorldField(workerData.seed),workerData.x,workerData.z);
 while(!job.done&&!isTerminating())job.step();
 const buildMs=performance.now()-start;
 let kind=0,base=0,index=0,metadata=false;
 while(!isTerminating()){
  const request=receiveMessageOnPort(parentPort);
  if(request===undefined){time.sleep_ms(1);continue;}
  if(!metadata){parentPort.postMessage(JSON.stringify({kind:"colliders",boxes:job.colliders}));metadata=true;continue;}
  while(kind<job.geometry.length&&base>=job.geometry[kind].v.length/8){kind++;base=0;index=0;}
  if(kind===job.geometry.length){parentPort.postMessage(JSON.stringify({kind:"done",buildMs:buildMs}));break;}
  const g=job.geometry[kind],end=Math.min(base+768,g.v.length/8),indices=[];
  // 768 is divisible by both the 24-vertex boxes and 4-vertex terrain patches.
  while(index<g.i.length&&g.i[index]<end){indices.push(g.i[index]-base);index++;}
  const vertices=g.v.slice(base*8,end*8);
  parentPort.postMessage(JSON.stringify({kind:"mesh",material:kind===11?8:kind,lod:kind===11?2:kind===6||kind===7||kind===8?1:0,vertices:vertices,indices:indices}));
  base=end;
 }
}catch(error){parentPort.postMessage(JSON.stringify({kind:"error",message:String(error)}));}
`;
fs.mkdirSync('assets/pbr',{recursive:true});
const output='// Generated by tools/create-world-worker.mjs; do not edit.\n'+compiled+'\n'+protocol;
if(process.argv.includes('--check')){
  if(fs.readFileSync('assets/pbr/world-worker.js','utf8')!==output)throw Error('World worker is stale; regenerate with node tools/create-world-worker.mjs');
}else fs.writeFileSync('assets/pbr/world-worker.js',output);
console.log('assets/pbr/world-worker.js');
